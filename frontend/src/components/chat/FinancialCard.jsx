import React from "react";
import { TrendingUp, PieChart, Landmark, ShieldCheck, Download, Calculator, DollarSign, Wallet } from "lucide-react";

export default function FinancialCard({ data, agent }) {
  if (!data) return null;

  // Helper to format currency in Indian numbering format
  const formatINR = (val) => {
    if (val === undefined || val === null) return "₹0";
    return `₹${Number(val).toLocaleString("en-IN")}`;
  };

  // 1. Loan EMI Card
  if (data.emi !== undefined && data.principal !== undefined) {
    const principal = Number(data.principal) || 0;
    const totalPayment = Number(data.totalPayment) || principal;
    const totalInterest = Number(data.totalInterest) || 0;
    const principalPercent = totalPayment > 0 ? Math.round((principal / totalPayment) * 100) : 100;
    const interestPercent = 100 - principalPercent;

    const handleDownload = () => {
      const summary = `FINASSIST BHARAT - LOAN EMI CALCULATION REPORT
--------------------------------------------------
Principal Loan Amount: ${formatINR(principal)}
Annual Interest Rate: ${data.annualRate}%
Tenure: ${data.years} years (${data.months} months)

Monthly EMI: ${formatINR(data.emi)}
Total Interest Payable: ${formatINR(totalInterest)}
Total Repayment Amount: ${formatINR(totalPayment)}

Principal Ratio: ${principalPercent}% | Interest Ratio: ${interestPercent}%
Generated by FinAssist Bharat Voice AI
(Note: Deterministic calculation. Not formal banking advice.)`;

      const blob = new Blob([summary], { type: "text/plain" });
      const url = URL.createObjectURL(blob);
      const a = document.createElement("a");
      a.href = url;
      a.download = `Loan_EMI_${principal}.txt`;
      a.click();
      URL.revokeObjectURL(url);
    };

    return (
      <div className="mt-3.5 p-4 rounded-xl bg-slate-950/70 border border-blue-500/30 shadow-lg text-slate-100">
        <div className="flex items-center justify-between pb-2.5 mb-3 border-b border-slate-800">
          <div className="flex items-center gap-2 text-blue-400 font-bold text-xs uppercase tracking-wider">
            <Landmark className="w-4 h-4" />
            <span>EMI Breakdown (Loan Agent)</span>
          </div>
          <button
            onClick={handleDownload}
            className="flex items-center gap-1 text-[11px] text-slate-400 hover:text-cyan-300 transition px-2 py-0.5 rounded bg-slate-800/80 hover:bg-slate-800"
            title="Download Calculation Report"
          >
            <Download className="w-3 h-3" />
            <span>Export</span>
          </button>
        </div>

        {/* Highlighted Monthly EMI Box */}
        <div className="flex flex-wrap items-baseline justify-between p-3 rounded-lg bg-gradient-to-r from-blue-900/40 via-indigo-900/30 to-slate-900 border border-blue-500/20 mb-3">
          <div>
            <span className="text-[11px] text-slate-400 block">Monthly Payable EMI</span>
            <span className="text-2xl font-extrabold text-transparent bg-clip-text bg-gradient-to-r from-blue-400 to-cyan-300">
              {formatINR(data.emi)}
            </span>
            <span className="text-xs text-slate-400 ml-1">/ month</span>
          </div>
          <div className="text-right text-xs">
            <span className="text-slate-400 block text-[11px]">Tenure &amp; Rate</span>
            <span className="font-semibold text-slate-200">
              {data.years} yrs @ {data.annualRate}%
            </span>
          </div>
        </div>

        {/* Visual Progress Bar (Principal vs Interest) */}
        <div className="space-y-1.5 mb-3">
          <div className="flex justify-between text-[11px] text-slate-400">
            <span className="flex items-center gap-1.5">
              <span className="w-2 h-2 rounded-full bg-cyan-400 inline-block" />
              Principal ({principalPercent}%)
            </span>
            <span className="flex items-center gap-1.5">
              <span className="w-2 h-2 rounded-full bg-amber-400 inline-block" />
              Interest ({interestPercent}%)
            </span>
          </div>
          <div className="w-full h-3 bg-slate-800 rounded-full overflow-hidden flex shadow-inner">
            <div
              style={{ width: `${principalPercent}%` }}
              className="bg-gradient-to-r from-cyan-500 to-blue-500 h-full transition-all duration-500"
            />
            <div
              style={{ width: `${interestPercent}%` }}
              className="bg-gradient-to-r from-amber-400 to-orange-500 h-full transition-all duration-500"
            />
          </div>
        </div>

        {/* Key Metrics Grid */}
        <div className="grid grid-cols-2 gap-2 text-xs pt-1">
          <div className="p-2 rounded bg-slate-900 border border-slate-800">
            <span className="text-slate-400 text-[11px] block">Loan Principal</span>
            <span className="font-bold text-slate-200">{formatINR(principal)}</span>
          </div>
          <div className="p-2 rounded bg-slate-900 border border-slate-800">
            <span className="text-slate-400 text-[11px] block">Total Interest</span>
            <span className="font-bold text-amber-300">{formatINR(totalInterest)}</span>
          </div>
          <div className="col-span-2 p-2 rounded bg-slate-900/60 border border-slate-800 flex justify-between items-center">
            <span className="text-slate-400 text-[11px]">Total Repayment (Principal + Interest)</span>
            <span className="font-bold text-cyan-200">{formatINR(totalPayment)}</span>
          </div>
        </div>
      </div>
    );
  }

  // 2. SIP Investment Card
  if (data.monthlyAmount !== undefined && data.totalValue !== undefined) {
    const invested = Number(data.investedAmount) || 0;
    const gain = Number(data.estimatedReturns) || 0;
    const total = Number(data.totalValue) || (invested + gain);
    const investedPercent = total > 0 ? Math.round((invested / total) * 100) : 50;
    const gainPercent = 100 - investedPercent;

    return (
      <div className="mt-3.5 p-4 rounded-xl bg-slate-950/70 border border-emerald-500/30 shadow-lg text-slate-100">
        <div className="flex items-center justify-between pb-2.5 mb-3 border-b border-slate-800">
          <div className="flex items-center gap-2 text-emerald-400 font-bold text-xs uppercase tracking-wider">
            <TrendingUp className="w-4 h-4" />
            <span>SIP Growth Projection (Investment Agent)</span>
          </div>
          <span className="text-[11px] px-2 py-0.5 rounded bg-emerald-950 text-emerald-300 border border-emerald-800">
            Expected {data.expectedRate}% p.a.
          </span>
        </div>

        {/* Expected Wealth Value */}
        <div className="p-3 rounded-lg bg-gradient-to-r from-emerald-950/40 via-teal-900/20 to-slate-900 border border-emerald-500/20 mb-3 flex items-baseline justify-between">
          <div>
            <span className="text-[11px] text-slate-400 block">Total Expected Corpus</span>
            <span className="text-2xl font-extrabold text-transparent bg-clip-text bg-gradient-to-r from-emerald-400 to-teal-300">
              {formatINR(total)}
            </span>
          </div>
          <div className="text-right text-xs">
            <span className="text-slate-400 block text-[11px]">SIP Tenure</span>
            <span className="font-semibold text-slate-200">{data.years} Years</span>
          </div>
        </div>

        {/* Visual Progress Bar (Invested vs Wealth Gain) */}
        <div className="space-y-1.5 mb-3">
          <div className="flex justify-between text-[11px] text-slate-400">
            <span className="flex items-center gap-1.5">
              <span className="w-2 h-2 rounded-full bg-slate-400 inline-block" />
              Invested ({investedPercent}%)
            </span>
            <span className="flex items-center gap-1.5">
              <span className="w-2 h-2 rounded-full bg-emerald-400 inline-block" />
              Estimated Gain ({gainPercent}%)
            </span>
          </div>
          <div className="w-full h-3 bg-slate-800 rounded-full overflow-hidden flex shadow-inner">
            <div
              style={{ width: `${investedPercent}%` }}
              className="bg-slate-500 h-full transition-all duration-500"
            />
            <div
              style={{ width: `${gainPercent}%` }}
              className="bg-gradient-to-r from-emerald-500 to-teal-400 h-full transition-all duration-500"
            />
          </div>
        </div>

        {/* 2-Column Metrics */}
        <div className="grid grid-cols-2 gap-2 text-xs">
          <div className="p-2 rounded bg-slate-900 border border-slate-800">
            <span className="text-slate-400 text-[11px] block">Monthly Deposit</span>
            <span className="font-bold text-slate-200">{formatINR(data.monthlyAmount)}</span>
          </div>
          <div className="p-2 rounded bg-slate-900 border border-slate-800">
            <span className="text-slate-400 text-[11px] block">Wealth Gain</span>
            <span className="font-bold text-emerald-400">+{formatINR(gain)}</span>
          </div>
        </div>
      </div>
    );
  }

  // 3. Fixed Deposit (FD) Card
  if (data.maturityAmount !== undefined && data.interestEarned !== undefined) {
    return (
      <div className="mt-3.5 p-4 rounded-xl bg-slate-950/70 border border-purple-500/30 shadow-lg text-slate-100">
        <div className="flex items-center justify-between pb-2.5 mb-3 border-b border-slate-800">
          <div className="flex items-center gap-2 text-purple-400 font-bold text-xs uppercase tracking-wider">
            <ShieldCheck className="w-4 h-4" />
            <span>Fixed Deposit Maturity (Investment Agent)</span>
          </div>
          <span className="text-[11px] px-2 py-0.5 rounded bg-purple-950 text-purple-300 border border-purple-800">
            {data.rate}% Annual Interest
          </span>
        </div>

        <div className="p-3 rounded-lg bg-gradient-to-r from-purple-950/40 via-indigo-950/20 to-slate-900 border border-purple-500/20 mb-3 flex items-baseline justify-between">
          <div>
            <span className="text-[11px] text-slate-400 block">Maturity Value</span>
            <span className="text-2xl font-extrabold text-purple-300">
              {formatINR(data.maturityAmount)}
            </span>
          </div>
          <div className="text-right text-xs">
            <span className="text-slate-400 block text-[11px]">Tenure</span>
            <span className="font-semibold text-slate-200">{data.years} Years</span>
          </div>
        </div>

        <div className="grid grid-cols-2 gap-2 text-xs">
          <div className="p-2 rounded bg-slate-900 border border-slate-800">
            <span className="text-slate-400 text-[11px] block">Deposit Amount</span>
            <span className="font-bold text-slate-200">{formatINR(data.amount)}</span>
          </div>
          <div className="p-2 rounded bg-slate-900 border border-slate-800">
            <span className="text-slate-400 text-[11px] block">Interest Earned</span>
            <span className="font-bold text-purple-400">+{formatINR(data.interestEarned)}</span>
          </div>
        </div>
      </div>
    );
  }

  // 4. Budget & Savings Card
  if (data.monthlyIncome !== undefined && data.savingsRate !== undefined) {
    const isHealthy = data.savingsRate >= 25;
    const isModerate = data.savingsRate >= 10 && data.savingsRate < 25;
    const statusColor = isHealthy ? "text-emerald-400" : isModerate ? "text-amber-400" : "text-rose-400";
    const statusBg = isHealthy ? "bg-emerald-500/10 border-emerald-500/30" : isModerate ? "bg-amber-500/10 border-amber-500/30" : "bg-rose-500/10 border-rose-500/30";

    return (
      <div className="mt-3.5 p-4 rounded-xl bg-slate-950/70 border border-teal-500/30 shadow-lg text-slate-100">
        <div className="flex items-center justify-between pb-2.5 mb-3 border-b border-slate-800">
          <div className="flex items-center gap-2 text-teal-400 font-bold text-xs uppercase tracking-wider">
            <Wallet className="w-4 h-4" />
            <span>Monthly Budget Evaluation (Budget Agent)</span>
          </div>
          <span className={`text-[11px] px-2 py-0.5 rounded border font-semibold ${statusBg} ${statusColor}`}>
            {data.status}
          </span>
        </div>

        <div className="grid grid-cols-3 gap-2 text-xs mb-3">
          <div className="p-2 rounded bg-slate-900 border border-slate-800">
            <span className="text-slate-400 text-[11px] block">Income</span>
            <span className="font-bold text-slate-200">{formatINR(data.monthlyIncome)}</span>
          </div>
          <div className="p-2 rounded bg-slate-900 border border-slate-800">
            <span className="text-slate-400 text-[11px] block">Expenses</span>
            <span className="font-bold text-rose-300">{formatINR(data.monthlyExpenses)}</span>
          </div>
          <div className="p-2 rounded bg-slate-900 border border-slate-800">
            <span className="text-slate-400 text-[11px] block">Savings</span>
            <span className="font-bold text-emerald-400">{formatINR(data.savings)}</span>
          </div>
        </div>

        {/* Savings Gauge */}
        <div className="space-y-1 text-xs">
          <div className="flex justify-between text-[11px] text-slate-400">
            <span>Savings Ratio</span>
            <span className="font-bold text-slate-200">{data.savingsRate}%</span>
          </div>
          <div className="w-full h-2.5 bg-slate-800 rounded-full overflow-hidden">
            <div
              style={{ width: `${Math.min(100, Math.max(0, data.savingsRate))}%` }}
              className={`h-full ${isHealthy ? "bg-emerald-500" : isModerate ? "bg-amber-500" : "bg-rose-500"} transition-all duration-500`}
            />
          </div>
        </div>
      </div>
    );
  }

  // 5. Loan Eligibility Card
  if (data.eligibleEMI !== undefined && data.estimatedLoanAmount !== undefined) {
    return (
      <div className="mt-3.5 p-4 rounded-xl bg-slate-950/70 border border-indigo-500/30 shadow-lg text-slate-100">
        <div className="flex items-center justify-between pb-2.5 mb-3 border-b border-slate-800">
          <div className="flex items-center gap-2 text-indigo-400 font-bold text-xs uppercase tracking-wider">
            <Landmark className="w-4 h-4" />
            <span>Loan Capacity Analysis (Loan Agent)</span>
          </div>
          <span className="text-[11px] px-2 py-0.5 rounded bg-indigo-950 text-indigo-300 border border-indigo-800">
            50% FOIR Rule
          </span>
        </div>

        <div className="grid grid-cols-2 gap-2 text-xs mb-3">
          <div className="p-2.5 rounded-lg bg-indigo-950/30 border border-indigo-500/20">
            <span className="text-slate-400 text-[11px] block">Eligible Monthly EMI</span>
            <span className="text-lg font-bold text-indigo-300">{formatINR(data.eligibleEMI)}</span>
          </div>
          <div className="p-2.5 rounded-lg bg-indigo-950/30 border border-indigo-500/20">
            <span className="text-slate-400 text-[11px] block">Max Loan Estimate</span>
            <span className="text-lg font-bold text-emerald-300">{formatINR(data.estimatedLoanAmount)}</span>
          </div>
        </div>

        <p className="text-[11px] text-slate-400 italic">
          Based on 50% Fixed Obligation to Income Ratio (FOIR). Actual loan disbursal depends on CIBIL score.
        </p>
      </div>
    );
  }

  return null;
}

